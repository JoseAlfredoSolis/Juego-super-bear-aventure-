// --- Camera + screen shake ---
const cam = { x:0, y:0 };
const shake = { t:0, dur:1, mag:0 };
function addShake(mag, dur) { shake.mag = Math.max(shake.mag, mag); shake.t = Math.max(shake.t, dur); shake.dur = Math.max(shake.dur, dur); }
function updateShake(dt) { if (shake.t > 0) { shake.t -= dt; if (shake.t <= 0) { shake.t = 0; shake.mag = 0; } } }
function camUpdate(px, py, levelW, snap=false) {
  const tx = clamp(px + PLAYER_W/2 - W/2, 0, levelW - W);
  const ty = clamp(py + PLAYER_H/2 - H/2, 0, 720 - H);
  if (snap) { cam.x = tx; cam.y = ty; }
  else { cam.x = lerp(cam.x, tx, 0.18); cam.y = lerp(cam.y, ty, 0.18); }
}
